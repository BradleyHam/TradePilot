import assert from 'node:assert/strict';
import {matchEmailJob, scannerIsStale} from '../lib/email-lead-routing';
import {normaliseParsedLead} from '../lib/email-lead-parser';
const lead={name:'Interior repaint',clientName:'Customer',clientEmail:'c@example.com',location:'1 Test Street',notes:'Please paint'};
const job={id:'1',name:lead.name,client_email:lead.clientEmail,location:lead.location,status:'lead',notes:'Original email: https://gmail/message'};
const input={followUp:false,threadJobIds:[]};
assert.equal(matchEmailJob([job],lead,input),'1');
assert.equal(matchEmailJob([{...job,name:'Cedar maintenance',status:'paid'}],lead,input),undefined);
assert.equal(matchEmailJob([job],{...lead,name:'New roof'},input),undefined);
assert.equal(matchEmailJob([job],lead,{...input,followUp:true}),'1');
assert.equal(matchEmailJob([job,{...job,id:'2'}],lead,{...input,followUp:true}),undefined);
assert.equal(matchEmailJob([job,{...job,id:'2'}],lead,{followUp:true,threadJobIds:['2']}),'2');
assert.equal(matchEmailJob([job,{...job,id:'2'}],lead,{followUp:true,threadJobIds:['1','2']}),undefined);
assert.equal(matchEmailJob([job],lead,{...input,originalLink:'https://gmail/message'}),'1');
assert.equal(scannerIsStale(null),false);
assert.equal(scannerIsStale(JSON.stringify({checkedAt:'2026-11-06T00:00:00Z'}),Date.parse('2026-11-06T01:00:00Z')),false);
assert.equal(scannerIsStale(JSON.stringify({checkedAt:'2026-11-06T00:00:00Z'}),Date.parse('2026-11-06T03:00:00Z')),true);
assert.equal(scannerIsStale('broken'),true);
assert.equal(normaliseParsedLead({looksLikeLead:false,confidence:'high',messageKind:'follow-up'}).messageKind,'follow-up');
console.log('Email routing and scanner health checks passed.');
